"""Regenerate eval/sample_qa.md from the live assistant."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from answer import Assistant

QS = ["What is the exit load of HDFC Flexi Cap Fund?", "What is the minimum SIP amount?", "What is the expense ratio?",
      "What is the benchmark of the scheme?", "What is the riskometer level?", "Is there a lock-in period? Is this an ELSS?",
      "How do I download my capital gains statement?", "Should I buy HDFC Flexi Cap Fund now?",
      "What were the 3-year returns of the fund?", "My PAN is ABCDE1234F, what is the exit load?"]
a = Assistant()
out = ["# Sample Q&A (generated by eval/run_samples.py)\n"]
for i, q in enumerate(QS, 1):
    r = a.ask(q)
    out.append(f"## {i}. {q}\n*Type: {r['kind']}*\n\n> " + r["answer"].replace("\n", "\n> ") + "\n")
(ROOT / "eval" / "sample_qa.md").write_text("\n".join(out))
print("ok")
